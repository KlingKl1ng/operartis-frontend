import * as XLSX from 'xlsx';
import { describe, expect, it } from 'vitest';
import { autoMapping, detectFormat, mappingComplete } from './mapping';
import { inspectFile, isValidSku, parseFile } from './workbook';

const sheetBytes = (rows: unknown[][]): ArrayBuffer => {
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet(rows), 'Sheet1');
  return XLSX.write(book, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer;
};

describe('recognising the file layout', () => {
  const days = (prefix: string) => Array.from({ length: 6 }, (_, index) => `${prefix}_D${index + 1}`);
  const dates = ['01.01.2026', '02.01.2026', '03.01.2026', '04.01.2026', '05.01.2026'];

  it('tells the five layouts apart', () => {
    expect(detectFormat(['SKU', 'Resid_Std', ...dates.slice(0, 3)])).toBe('operartis_residual');
    expect(detectFormat(['SKU', ...dates.map((d) => `P50_${d}`), ...dates.map((d) => `P90_${d}`)])).toBe('forecaster_prefixed');
    expect(detectFormat(['SKU_ID', ...days('P50'), ...days('P90')])).toBe('horizontal');
    expect(detectFormat(['Item', ...dates])).toBe('forecaster');
    expect(detectFormat(['SKU_ID', 'Date', 'P50', 'P90'])).toBe('vertical');
  });

  it('needs more than five day columns of each kind for the P50_D layout', () => {
    expect(detectFormat(['SKU_ID', ...days('P50').slice(0, 5), ...days('P90').slice(0, 5)])).toBe('vertical');
  });

  it('proposes columns and locks the parameters it found in the file', () => {
    const { mapping, locks } = autoMapping(['SKU_ID', 'Date', 'P50', 'P90', 'Initial_Stock', 'Lead_Time_Days']);
    expect(mapping).toMatchObject({ format: 'vertical', sku_id: 'SKU_ID', date: 'Date', p50: 'P50', p90: 'P90', initial_stock: 'Initial_Stock', lead_time_mean: 'Lead_Time_Days', review_period: '' });
    expect(locks).toEqual({ initial_stock: true, lead_time_mean: true, lead_time_std: false, review_period: false, min_order_qty: false, target_service_level: false });
    expect(mappingComplete(mapping)).toBe(true);
    expect(mappingComplete({ ...mapping, p90: '' })).toBe(false);
  });

  it('skips footer rows that are not products', () => {
    expect(isValidSku('FAST-0001')).toBe(true);
    for (const text of ['', null, '© 2026 Operartis Analytics. All rights reserved.', 'Total: 12', 'Page 2', 'Generated by Operartis']) {
      expect(isValidSku(text)).toBe(false);
    }
  });
});

describe('reading forecasts', () => {
  it('starts a P50_D file without a start date on the given day', () => {
    const header = ['SKU_ID', ...Array.from({ length: 6 }, (_, i) => `P50_D${i + 1}`), ...Array.from({ length: 6 }, (_, i) => `P90_D${i + 1}`)];
    const data = sheetBytes([header, ['A', 10, 11, 12, 13, 14, 15, 20, 21, 22, 23, 24, 25]]);
    const { headers, metadata } = inspectFile(data);
    const parsed = parseFile(data, autoMapping(headers, metadata).mapping, { today: new Date(2026, 9, 24) });
    expect(parsed.grouped.A.map((point) => point.date)).toEqual(['2026-10-24', '2026-10-25', '2026-10-26', '2026-10-27', '2026-10-28', '2026-10-29']);
    expect(parsed.grouped.A[0]).toEqual({ date: '2026-10-24', p50: 10, p90: 20 });
  });

  it('derives a missing P90 as 1.3 times P50 and keeps a day without demand', () => {
    const data = sheetBytes([['SKU', 'Date', 'P50', 'P90'], ['A', '2026-01-01', 10, null], ['A', '2026-01-02', 0, 0], ['A', '2026-01-03', 5, 9], ['A', '2026-01-04', null, 9]]);
    const { headers } = inspectFile(data);
    const parsed = parseFile(data, autoMapping(headers).mapping);
    // A forecast of 0 is a day without demand and stays; a row without a forecast is no day at all.
    expect(parsed.grouped.A).toEqual([{ date: '2026-01-01', p50: 10, p90: 13 }, { date: '2026-01-02', p50: 0, p90: 0 }, { date: '2026-01-03', p50: 5, p90: 9 }]);
  });

  it('reports no products when nothing usable is mapped', () => {
    const data = sheetBytes([['SKU', 'Date', 'P50', 'P90'], ['A', '2026-01-01', null, 4], ['A', '2026-01-02', 'n/a', 4]]);
    expect(parseFile(data, autoMapping(inspectFile(data).headers).mapping).skus).toEqual([]);
  });
});
