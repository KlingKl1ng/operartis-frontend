#!/usr/bin/env node
// Generates why-aps.html and platform.html from index.html.
//
// index.html is the single source for the three landing pages. Which page it renders is decided by the
// data-page attribute on <html> (see PAGE in index.html); the generated copies differ only in that
// attribute and in their <head> metadata.
//
//   node build-landing-pages.mjs           write the generated pages (run after every change to index.html)
//   node build-landing-pages.mjs --check   exit 1 if a generated page is out of date (used by the tests)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)));

const HOME = {
  title: 'Operartis | An Optimization System For The Entire Supply Chain',
  description: 'Operartis is an APS optimization platform that transforms ERP and MES data into actionable plans across the supply chain.',
  socialDescription: 'An APS optimization platform that transforms ERP and MES data into actionable plans across the supply chain.',
  url: 'https://operartis.io/',
};

const PAGES = {
  'why-aps': {
    title: 'Operartis | Why APS',
    description: 'Why ERP and MES alone are not enough: their limits, the four levels of analytics, and the mathematical foundation behind provable optimization.',
    url: 'https://operartis.io/why-aps',
  },
  platform: {
    title: 'Operartis | The APS Platform',
    description: 'The Operartis APS matrix: optimization modules across strategic, tactical, operational and cross-functional planning, from network design to daily routing.',
    url: 'https://operartis.io/platform',
  },
};

function replaceExactly(html, from, to, count, page) {
  const found = html.split(from).length - 1;
  if (found !== count) {
    throw new Error(`build-landing-pages: expected ${count} × ${JSON.stringify(from.slice(0, 70))} in index.html, found ${found} (page ${page})`);
  }
  return html.split(from).join(to);
}

export function buildPage(source, page) {
  const meta = PAGES[page];
  let html = source;
  const swap = (from, to, count = 1) => { html = replaceExactly(html, from, to, count, page); };

  swap('<!DOCTYPE html>\n<html lang="en">',
    `<!DOCTYPE html>\n<!-- GENERATED from index.html by build-landing-pages.mjs. Do not edit this file: change index.html, then run "node build-landing-pages.mjs". -->\n<html lang="en" data-page="${page}">`);
  swap(`<title>${HOME.title}</title>`, `<title>${meta.title}</title>`);
  swap(`<meta name="description" content="${HOME.description}">`, `<meta name="description" content="${meta.description}">`);
  swap(`<link rel="canonical" href="${HOME.url}">`, `<link rel="canonical" href="${meta.url}">`);
  swap(`<meta property="og:url" content="${HOME.url}">`, `<meta property="og:url" content="${meta.url}">`);
  swap(`<meta property="og:title" content="${HOME.title}">`, `<meta property="og:title" content="${meta.title}">`);
  swap(`<meta property="og:description" content="${HOME.socialDescription}">`, `<meta property="og:description" content="${meta.description}">`);
  swap(`<meta name="twitter:title" content="${HOME.title}">`, `<meta name="twitter:title" content="${meta.title}">`);
  swap(`<meta name="twitter:description" content="${HOME.socialDescription}">`, `<meta name="twitter:description" content="${meta.description}">`);

  // The Organization record belongs to the home page only
  const start = html.indexOf('    <script type="application/ld+json">');
  const end = html.indexOf('    </script>\n', start);
  if (start === -1 || end === -1) throw new Error('build-landing-pages: Organization JSON-LD block not found in index.html');
  html = html.slice(0, start) + html.slice(end + '    </script>\n'.length).replace(/^\n/, '');
  return html;
}

function main() {
  const check = process.argv.includes('--check');
  const source = readFileSync(resolve(root, 'index.html'), 'utf8');
  let stale = 0;
  for (const page of Object.keys(PAGES)) {
    const file = resolve(root, `${page}.html`);
    const next = buildPage(source, page);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === next) {
      console.log(`${page}.html is up to date`);
    } else if (check) {
      console.error(`${page}.html is out of date — run "node build-landing-pages.mjs"`);
      stale += 1;
    } else {
      writeFileSync(file, next);
      console.log(`${page}.html written`);
    }
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
